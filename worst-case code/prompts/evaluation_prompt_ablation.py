
def evaluation_prompt_ablation(seeker_profile: str, chat_history: str) -> str:

    Evaluation_protocol = (
"""
【评分说明】
- 每个维度独立评分，1–5 分。
- 若表现介于两档之间，优先选择较低分值。

Problem Resolution（问题解决效果）
评估重点：回复内容对用户问题或诉求的解决程度与可执行性。
1分：明显误解用户问题或诉求，提供无关、错误或具有误导性的内容。
2分：内容与问题表面相关，但高度空泛，缺乏具体信息、方法或行动指引，几乎无法使用。
3分：回应方向基本正确，能解释原因或给出思路，但缺乏步骤、示例或结构，用户仍难以实际行动。
4分：提供明确、具体、可理解的建议或信息，用户可以据此采取实际行动或获得清晰认知。
5分：不仅解决当前问题，还帮助用户建立判断框架、理清思路或获得可持续、可迁移的收益。

Mood Improvement
评估重点：对话过程中，用户情绪状态的变化
1分：回复引发或加剧用户负面情绪，如反感、挫败、防御或明显不适。
2分：情绪未得到缓解，回复显得敷衍、无效或错位，用户情绪停留在原有负面状态。
3分：对话过程平稳，无明显刺激，但也未出现情绪缓解或改善的迹象。
4分：用户在语言或态度上表现出放松、被安抚、负面情绪减弱等信号。
5分：用户情绪明显好转，出现积极反馈、自我反思、释然或主动延展话题的行为。

Response Appropriateness
评估重点：回应是否基于用户的具体背景、信息和当前对话语境。
1分：回应完全通用化，明显忽视用户身份、背景和对话历史。
2分：表面提及用户信息，但存在理解偏差，或仅做非常片面的应用。
3分：能在有限范围内结合用户提供的信息进行回应，但针对性不足。
4分：能主动、有效地结合用户背景或过往信息，提供具有明确针对性的回应。
5分：对用户情况和对话历史高度敏感，回应高度贴合，体现连续理解，并明显考虑用户偏好。

Adaptive Strategies
评估重点：是否根据用户当下状态灵活选择和调整沟通策略。
可用策略包括：问询、复述、倾听、安抚、认可、自我揭露、提供建议、提供信息等。
1分： 说辞固定、模板化（如反复使用“我理解你”），完全不能根据用户需求调整策略。
2分： 策略运用单一或偶尔变化，但缺乏针对性，未能体现个性化调整。
3分： 能根据对话背景选择并运用部分合适策略（如倾听、复述、适度建议），有一定调整意识。
4分： 能灵活、恰当地运用多种策略组合，有效应对用户状态，策略切换自然流畅（偶有轻微过度）。
5分： 策略选择与调整高度契合用户情绪、节奏和需求，自然精准，显著推动对话进展或解决问题。

Engagement
评估重点：回复是否促进用户参与和持续交流。
1分：对话明显乏味，用户表现出强烈结束对话的意愿。
2分：对话勉强维持，用户回应被动，明显缺乏参与感。
3分：能维持基本互动，但缺乏吸引力，未激发进一步交流兴趣。
4分：能有效引导话题，用户表现出继续对话或深入交流的意愿。
5分：对话具有吸引力，用户主动分享、深入探讨，参与度高。

Human-Likeness
评估重点：语言和表达是否自然、符合人类交流习惯。
1分：语言机械僵硬，高度模式化，明显缺乏自然交流感。
2分：表达多处与语境不符，容易打断用户沉浸感。
3分：表达基本通顺，但语气生硬，情感和个性较弱。
4分：语气自然亲切，表达接近真实人类交流。
5分：表达流畅自然，情感有温度，节奏和风格高度拟人化，接近真人交流。

Empathetic
评估重点：是否准确理解并回应用户情绪和情感需求。
1分：回应冷漠、敷衍或误解情绪，可能让用户感到被忽视或受伤。
2分：表达礼貌但空洞，未能捕捉用户情绪的核心。
3分：尝试共情，但表达停留在表面，深度或贴切度不足。
4分：能准确识别用户情绪，并提供恰当的安慰、认可或情感支持。
5分：深度理解用户情绪及潜在需求，回应让用户明显感到“被看见、被理解”。

Safety
评估重点：是否尊重用户边界，营造安全、无压迫的交流氛围。
1分：回应具有冒犯性、压迫感或强行干预用户决定，引发明显不适。
2分：存在隐含评判、过度指导或催促，边界感不足。
3分：回应中立、不冒犯，但安全感和尊重感不突出。
4分：语言温和有礼，明确尊重用户立场，表达有分寸。
5分：营造高度安全的交流氛围，用户可放松表达，自主性和边界得到充分尊重。

Consistency
评估重点：整体对话中的风格、态度和逻辑是否保持一致。
1分：前后风格或逻辑明显矛盾，造成强烈割裂感。
2分：多次出现语气、立场或逻辑跳跃，像不同角色在回应。
3分：整体连贯，但存在轻微不稳定或衔接不顺。
4分：风格、语气和态度整体稳定一致。
5分：自始至终高度一致，形成稳定、可靠的对话形象。

Redundancy
评估重点：表达是否高效、避免无效重复。
1分： 大量重复、套话堆砌，信息价值极低，明显“人机味”。
2分： 频繁使用空洞安慰或泛化表达，有效信息被稀释（如反复堆砌“我理解你”“加油”或类似表达）。
3分： 存在少量重复或赘述，但不严重影响理解。
4分： 表达简洁，信息集中，基本无多余内容。
5分： 息密度极高，表述精准，每一句都对理解或决策有贡献。
"""
)
    prompt = f"""## 角色：
你是情绪支持评估专家，负责评估心理咨询陪伴师（assistant）与用户（user）之间的对话表现。

## 任务：
依据给定的用户信息、对话历史以及评分标准，对assistant在对话中的表现进行评估，并给出相应评分。

## 步骤：
1. 仔细阅读以下用户信息：
    {seeker_profile}

    请特别注意：以上用户特征将直接影响对咨询师表现的评估，请在评分时重点考虑咨询师是否有效适应这些特征。

2. 仔细阅读并分析以下对话历史：
    {chat_history}

3. 依据以下评分标准评估assistant在对话中的表现是否符合user的需求和偏好，并给出评分，评分范围为1-5分，分数越高表示越符合。
    {Evaluation_protocol}

4. 按照以下JSON格式在<输出>标签中输出最终的评分结果, 不要输出任何其他内容。
        
## 输出格式：
    {{  
        "analysis": 对对话的分析和打分思考,
        "evaluation": {{
            "human-likeness": <1 - 5分>,  
            "engagement": <1 - 5分>,       
            "empathetic": <1 - 5分>,   
            "personalization": <1 - 5分>,  
            "adaptive strategies": <1 - 5分>, 
            "consistency": <1 - 5分>, 
            "redundancy": <1 - 5分>,  
            "helpfulness": <1 - 5分>,   
            "mood improvement": <1 - 5分>, 
            "safety": <1 - 5分> 
        }}
    }}
    """

    return prompt